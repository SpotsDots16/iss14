using Content.Client.UserInterface.Controls;
using Content.Shared.Xenoarchaeology.Equipment;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client.Xenoarchaeology.Ui;

[GenerateTypedNameReferences]
public sealed partial class PeerReviewConsoleWindow : DefaultWindow
{
    private const string ResearchPanelBackground = "#2B2D40";

    private static readonly SpriteSpecifier.Rsi StoredDataSprite =
        new(new ResPath("Objects/Misc/bureaucracy.rsi"), "paper_dotmatrix_words");

    private static readonly SpriteSpecifier.Rsi MinorPublicationSprite =
        new(new ResPath("Objects/Misc/bureaucracy.rsi"), "paper");

    private static readonly SpriteSpecifier.Rsi SignificantPublicationSprite =
        new(new ResPath("Objects/Misc/bureaucracy.rsi"), "paper_words");

    private static readonly SpriteSpecifier.Rsi MajorPublicationSprite =
        new(new ResPath("Objects/Misc/bureaucracy.rsi"), "acquisition_form_words");

    public event Action<PublicationTier>? PublishRequested;

    public PeerReviewConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        StoredDataIcon.SetFromSpriteSpecifier(StoredDataSprite);
        MinorPublicationIcon.SetFromSpriteSpecifier(MinorPublicationSprite);
        SignificantPublicationIcon.SetFromSpriteSpecifier(SignificantPublicationSprite);
        MajorPublicationIcon.SetFromSpriteSpecifier(MajorPublicationSprite);

        HeaderPanel.PanelOverride = CreatePanel(ResearchPanelBackground, "#69B98A", new Thickness(0, 0, 0, 2));
        StoredDataPanel.PanelOverride = CreatePanel(ResearchPanelBackground, "#65B583", new Thickness(4, 0, 0, 0));

        MinorPublicationPanel.PanelOverride = CreatePanel(ResearchPanelBackground, "#4F9B70", new Thickness(4, 0, 0, 0));
        SignificantPublicationPanel.PanelOverride = CreatePanel(ResearchPanelBackground, "#63B982", new Thickness(4, 0, 0, 0));
        MajorPublicationPanel.PanelOverride = CreatePanel(ResearchPanelBackground, "#82D19D", new Thickness(4, 0, 0, 0));

        StoredValueLabel.Text = Loc.GetString("peer-review-window-units", ("count", 0));
        StoredStatusLabel.Text = Loc.GetString("peer-review-window-status-waiting");

        UpdatePublication(MinorProgressBar, MinorRequirementLabel, PublishSmallButton,
            0, PeerReviewConsoleConstants.SmallPublicationCost);
        UpdatePublication(SignificantProgressBar, SignificantRequirementLabel, PublishMediumButton,
            0, PeerReviewConsoleConstants.MediumPublicationCost);
        UpdatePublication(MajorProgressBar, MajorRequirementLabel, PublishLargeButton,
            0, PeerReviewConsoleConstants.LargePublicationCost);

        PublishSmallButton.OnPressed += _ =>
            PublishRequested?.Invoke(PublicationTier.Small);

        PublishMediumButton.OnPressed += _ =>
            PublishRequested?.Invoke(PublicationTier.Medium);

        PublishLargeButton.OnPressed += _ =>
            PublishRequested?.Invoke(PublicationTier.Large);
    }

    public void UpdateState(PeerReviewConsoleUiState state)
    {
        StoredValueLabel.Text = Loc.GetString("peer-review-window-units", ("count", state.StoredValue));

        StoredStatusLabel.Text = state.StoredValue switch
        {
            >= PeerReviewConsoleConstants.LargePublicationCost =>
                Loc.GetString("peer-review-window-status-major"),

            >= PeerReviewConsoleConstants.MediumPublicationCost =>
                Loc.GetString("peer-review-window-status-significant"),

            >= PeerReviewConsoleConstants.SmallPublicationCost =>
                Loc.GetString("peer-review-window-status-minor"),

            _ => Loc.GetString("peer-review-window-status-waiting"),
        };

        UpdatePublication(MinorProgressBar, MinorRequirementLabel, PublishSmallButton,
            state.StoredValue, PeerReviewConsoleConstants.SmallPublicationCost);
        UpdatePublication(SignificantProgressBar, SignificantRequirementLabel, PublishMediumButton,
            state.StoredValue, PeerReviewConsoleConstants.MediumPublicationCost);
        UpdatePublication(MajorProgressBar, MajorRequirementLabel, PublishLargeButton,
            state.StoredValue, PeerReviewConsoleConstants.LargePublicationCost);
    }

    private void UpdatePublication(
        ProgressBar progressBar,
        Label requirementLabel,
        Button publishButton,
        int storedValue,
        int cost)
    {
        var current = Math.Min(storedValue, cost);
        var remaining = Math.Max(cost - storedValue, 0);

        progressBar.MaxValue = cost;
        progressBar.Value = current;
        requirementLabel.Text = Loc.GetString("peer-review-window-progress",
            ("current", current),
            ("required", cost));

        publishButton.Disabled = remaining > 0;
        publishButton.Text = remaining > 0
            ? Loc.GetString("peer-review-window-requires-short", ("count", remaining))
            : Loc.GetString("peer-review-window-publish");
    }

    private static StyleBoxFlat CreatePanel(string backgroundColor, string borderColor, Thickness borderThickness)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex(backgroundColor),
            BorderColor = Color.FromHex(borderColor),
            BorderThickness = borderThickness,
        };
    }
}
